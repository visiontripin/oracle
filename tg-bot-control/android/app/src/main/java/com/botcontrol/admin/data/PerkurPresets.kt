    fun schedule(): List<ScheduleEvent> {
        val daily = listOf(
            ScheduleEvent(text = "🌙 Спокойной ночи", hour = 0, minute = 0),
            ScheduleEvent(text = "☀️ Доброе утра ёпта", hour = 6, minute = 0),
            ScheduleEvent(text = "за Сонькой ❤️", hour = 18, minute = 55),
        )
        val weekdays = listOf(8 to 55, 9 to 55, 10 to 55, 11 to 30, 12 to 55, 13 to 55, 14 to 55)
            .map { (h, m) ->
                val smoke = h != 11
                ScheduleEvent(
                    hour = h, minute = m,
                    text = if (smoke) "🔥 ПЕРЕКУР" else "🍽 ОБЕД",
                    days = listOf(1, 2, 3, 4, 5),
                    menu = if (smoke) smokeMenu() else emptyList(),
                )
            }
        val monThu = listOf(
            ScheduleEvent(hour = 15, minute = 55, text = "🔥 ПЕРЕКУР",
                days = listOf(1, 2, 3, 4), menu = smokeMenu()),
            ScheduleEvent(hour = 16, minute = 55, text = "до завтра!",
                days = listOf(1, 2, 3, 4)),
        )
        val friday = listOf(
            ScheduleEvent(hour = 15, minute = 55, text = "🔥 ПЕРЕКУР и до завтра!",
                days = listOf(5), menu = smokeMenu()),
        )
        return daily + weekdays + monThu + friday
    }

