# ---------- дайджесты канала: 10:20 и 20:40, тексты чередуются ----------
def get_today_schedule(now):
    schedule = [
        (10, 20, "»канал 🌅 Доброе утро! Проверь новые вещи — может, ваше уже ждёт. | ☀️ Утро! Свежие вещи в канале — забирайте, пока даром. | 🌅 Новый день — новые находки! Загляните в свежие посты."),
        (20, 40, "»канал 🌙 Вечерняя проверка: вещи всё ещё ищут хозяев! | 🌆 Вечер в самом разгаре — посмотрите, что отдали сегодня. | 🌙 Перед сном: вдруг ваша вещь пришла вечером?"),
    ]
    wd = now.weekday()
    if wd < 5:
        schedule.extend([
            (13, 0, "»канал 🔁 Раз в будни: напомните себе отметить «отдано», если вещь нашла хозяина."),
        ])
    return sorted(schedule, key=lambda item: (item[0], item[1]))

