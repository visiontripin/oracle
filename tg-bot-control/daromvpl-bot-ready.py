# ---------- расписание: дайджест для админа канала ----------
def get_today_schedule(now):
    schedule = [
        (9, 0, "🌅 Доброе утро! Проверь новые вещи и запросы на удаление"),
        (21, 0, "🌙 Итоги дня: сколько вещей нашли хозяев? Отметь «отдано»"),
    ]
    wd = now.weekday()
    if wd < 5:
        schedule.extend([
            (13, 0, "🔁 Подними объявления — вечер самая активная аудитория"),
        ])
    return sorted(schedule, key=lambda item: (item[0], item[1]))
