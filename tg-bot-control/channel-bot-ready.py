# ---------- расписание: напоминания админу канала ----------
def get_today_schedule(now):
    schedule = [
        (10, 0, "📢 Пора опубликовать новые объявления"),
    ]
    wd = now.weekday()
    if wd < 5:
        schedule.extend([
            (13, 30, "🔁 Проверь сообщения и подними объявления"),
            (19, 0, "📊 Итог дня: сколько объявлений опубликовано"),
        ])
    return sorted(schedule, key=lambda item: (item[0], item[1]))
