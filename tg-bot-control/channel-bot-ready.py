# ---------- команды ----------
@bot.message_handler(commands=["start"])
def cmd_start(msg):
    bot.send_message(msg.chat.id, "Привет! Пришли описание товара — оформлю объявление для канала.\nНапример: «кресло, 3000 руб, Москва, почти новое».", )

@bot.message_handler(commands=["help"])
def cmd_help(msg):
    bot.send_message(
        msg.chat.id,
        "Как публиковать:\n"
        "1. Пришли описание товара текстом.\n"
        "2. Я оформлю объявление по шаблону канала.\n"
        "3. Готовый текст уходит в канал, покупатели пишут тебе в личку.\n"
        "\n"
        "Команды:\n"
        "/start — краткая справка\n"
        "/help — эта памятка",
    )

